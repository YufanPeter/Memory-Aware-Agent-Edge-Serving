def render_example(ex: dict, explain: bool) -> str:
    lines = [f"Question: {ex['question']}"]
    for i, (thought, action, obs) in enumerate(ex["steps"], 1):
        lines += [f"Thought {i}: {thought}", f"Action {i}: {action}", f"Observation {i}: {obs}"]
    n = len(ex["steps"]) + 1
    thought, answer, explanation = ex["final"]
    lines.append(f"Thought {n}: {thought}")
    lines.append(f"Action {n}: finish[{answer}]")
    if explain:
        lines.append(f"Explanation: {explanation}")
    return "\n".join(lines)


def react_system(few_shot: int, explain: bool) -> str:
    parts = [REACT_RULES]
    if explain:
        parts.append(EXPLAIN_RULE)
    if few_shot > 0:
        examples = "\n\n".join(render_example(ex, explain) for ex in EXAMPLES[:few_shot])
        parts.append("Here are some examples.\n\n" + examples)
    return "\n\n".join(parts)


@dataclass
class Prompt:
    segments: list[tuple[str, str]] = field(default_factory=list)   # (kind, text)

    def add(self, kind: str, text: str) -> None:
        if text:
            self.segments.append((kind, text))

    def extend(self, pieces: list[tuple[str, str]]) -> None:
        for kind, text in pieces:
            self.add(kind, text)

    @property
    def text(self) -> str:
        return "".join(t for _, t in self.segments)
